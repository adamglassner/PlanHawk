"""Builds PlanHawk's icon fonts from Microsoft's Fluent UI System Icons (MIT) and writes the matching C# constants.

Each icon gets a private-use code point; the app refers to icons by name through the Ic class (Models/Ic.cs),
e.g. Text="{x:Static m:Ic.Home}" in XAML or Ic.Home in code.

    python tools/make_icon_font.py <path to fluentui-system-icons/fonts>

Output: src/PlanHawk.Desktop/Assets/Fonts/PlanHawkIcons-{Regular,Filled}.ttf and src/PlanHawk.Desktop/Models/Ic.cs
"""
import json, sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._c_m_a_p import cmap_format_4

# C# name -> Fluent icon name. Code points are assigned in this order from U+E000, so only ever append.
ICONS = [
    ('Home', 'home'), ('Gantt', 'gantt_chart'), ('Task', 'task_list_ltr'), ('Timeline', 'timeline'), ('Board', 'board'),
    ('Calendar', 'calendar_ltr'), ('Resources', 'people_team'), ('Person', 'person'), ('People', 'people'), ('PersonAdd', 'people_add'),
    ('Report', 'data_bar_vertical'), ('Money', 'money'), ('Link', 'link'), ('Unlink', 'link_dismiss'), ('Milestone', 'diamond'),
    ('Flag', 'flag'), ('FlagDone', 'flag_checkered'), ('Settings', 'settings'), ('Sun', 'weather_sunny'), ('Moon', 'weather_moon'),
    ('Add', 'add'), ('Search', 'search'), ('ChevronDown', 'chevron_down'), ('ChevronRight', 'chevron_right'), ('ChevronLeft', 'chevron_left'),
    ('More', 'more_horizontal'), ('Star', 'star'), ('Filter', 'filter'), ('Sort', 'arrow_sort'), ('Clock', 'clock'),
    ('Check', 'checkmark'), ('CheckCircle', 'checkmark_circle'), ('Dismiss', 'dismiss'), ('Folder', 'folder'), ('FolderOpen', 'folder_open'),
    ('Download', 'arrow_download'), ('Sparkle', 'sparkle'), ('Cloud', 'cloud'), ('Info', 'info'), ('Alert', 'alert'),
    ('Warning', 'warning'), ('Indent', 'text_indent_increase_ltr'), ('Outdent', 'text_indent_decrease_ltr'), ('ZoomIn', 'zoom_in'), ('ZoomOut', 'zoom_out'),
    ('ZoomFit', 'zoom_fit'), ('Undo', 'arrow_undo'), ('Redo', 'arrow_redo'), ('Save', 'save'), ('Print', 'print'),
    ('Export', 'arrow_export_ltr'), ('Import', 'arrow_import'), ('Split', 'arrow_split'), ('Branch', 'branch'), ('Target', 'target'),
    ('Trending', 'arrow_trending'), ('Template', 'document_one_page'), ('Delete', 'delete'), ('Briefcase', 'briefcase'), ('Document', 'document_text'),
    ('Clipboard', 'clipboard_task'), ('Lock', 'lock_closed'), ('Sync', 'arrow_sync'), ('Help', 'question_circle'), ('Mail', 'mail'),
    ('Grid', 'grid_dots'), ('Circle', 'circle'), ('Table', 'table'), ('Columns', 'column_triple'), ('Pin', 'pin'),
    ('History', 'history'), ('Eye', 'eye'), ('ArrowRight', 'arrow_right'), ('Unchecked', 'checkbox_unchecked'), ('Checked', 'checkbox_checked'),
    ('Pdf', 'document_pdf'), ('Idea', 'lightbulb'), ('Wrench', 'wrench'), ('Today', 'calendar_day'), ('Month', 'calendar_month'),
    ('Chart', 'chart_multiple'), ('Tree', 'list_bar_tree'), ('Shared', 'share'), ('Routing', 'arrow_routing'), ('Status', 'status'),
]
CP = {name: 0xE000 + i for i, (name, _) in enumerate(ICONS)}


def build(src_dir, style, family, out_dir):
    names = json.load(open(f'{src_dir}/FluentSystemIcons-{style}.json'))
    font = TTFont(f'{src_dir}/FluentSystemIcons-{style}.ttf')
    cmap = font.getBestCmap()
    chosen = {}
    for name, fluent in ICONS:
        for size in (20, 24, 16, 28):
            key = f'ic_fluent_{fluent}_{size}_{style.lower()}'
            if key in names:
                chosen[CP[name]] = cmap[names[key]]
                break
        else:
            sys.exit(f'missing icon: {fluent} ({style})')
    opts = subset.Options()
    opts.glyph_names = True
    opts.notdef_outline = True
    opts.name_IDs = ['*']
    opts.layout_features = []
    sub = subset.Subsetter(opts)
    sub.populate(glyphs=sorted(set(chosen.values())))
    sub.subset(font)
    table = cmap_format_4(4)
    table.platformID, table.platEncID, table.language = 3, 1, 0
    table.cmap = chosen
    font['cmap'].tables = [table]
    for rec in font['name'].names:
        if rec.nameID in (1, 4, 16):
            rec.string = family
        elif rec.nameID == 6:
            rec.string = family.replace(' ', '')
        elif rec.nameID in (2, 17):
            rec.string = 'Regular'
    out = f'{out_dir}/PlanHawkIcons-{style}.ttf'
    font.save(out)
    print(out, len(chosen), 'icons')


def write_constants(path):
    lines = [
        '// Generated by tools/make_icon_font.py. Do not edit by hand; add icons there and re-run it.',
        'namespace PlanHawk.Models;',
        '',
        '/// <summary>Icon glyphs in the PlanHawk icon fonts (Fluent UI System Icons). XAML: {x:Static m:Ic.Home}.</summary>',
        'public static class Ic',
        '{',
    ]
    for name, fluent in ICONS:
        lines.append(f'    public const string {name} = "\\u{CP[name]:04X}"; // {fluent}')
    lines.append('}')
    open(path, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print(path)


if __name__ == '__main__':
    src = sys.argv[1]
    out = 'src/PlanHawk.Desktop/Assets/Fonts'
    build(src, 'Regular', 'PlanHawk Icons', out)
    build(src, 'Filled', 'PlanHawk Icons Filled', out)
    write_constants('src/PlanHawk.Desktop/Models/Ic.cs')
